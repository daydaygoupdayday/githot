# 正文里不许出现的数据区 JSON 键名（写进中文句子会立刻暴露是机器稿）
BANNED_FIELD_NAMES = [
    "stars_per_day", "created_at", "pushed_at", "open_issues", "forks_count",
    "min_stars", "days_age", "board_type", "board_label", "generated_at",
    "homepage", "license", "topics", "stars", "forks", "rank", "details",
    "description", "author", "path",
]

# 模板残留：早期 prompt 逼模型产出的清单化写法，出现即说明还是模板稿
BANNED_PATTERNS = [
    r"第\s*\d+\s*名\s*[|｜]",
    r"\*\*作者[:：]\*\*",
    r"\*\*星标数[:：]\*\*",
    r"创建时间[:：]",
    r"一句话卖点",
    r"关注我|关注公众号|阅读原文",
    r"地址是\s*\[",
]


def _banned_phrase_line() -> str:
    return "、".join(BANNED_PHRASES[:14]) + "、" + "、".join(BANNED_PHRASES[14:])


def _banned_field_line() -> str:
    return "、".join(f"`{n}`" for n in BANNED_FIELD_NAMES)


def lint_article(text: str) -> dict:
    """自检一篇文章的"机器味"信号，返回问题清单（供调用方决定是否重写）。

    三类信号：套话词、JSON 字段名漏进正文、模板残留句式。
    另外给出结构指标：各节字数变异系数（越接近 0 越像模板）、句长变异系数。
    """
    import re
    import statistics

    hits = [w for w in BANNED_PHRASES if w in text]
    fields = [f for f in BANNED_FIELD_NAMES if re.search(rf"\b{re.escape(f)}\b", text)]
    patterns = [p for p in BANNED_PATTERNS if re.search(p, text)]

    def _cv(nums):
        return round(statistics.pstdev(nums) / statistics.mean(nums), 3) if len(nums) > 1 and statistics.mean(nums) else 0.0

    def _len(s):
        return len(re.sub(r"\s+", "", s))

    sections = [b for b in re.split(r"\n(?=##\s)", text) if _len(b) > 30]
    sentences = [p for p in re.split(r"[。！？\n]+", re.sub(r"^#+.*$", "", text, flags=re.M))
                 if _len(p) >= 4]

    return {
        "套话": hits,
        "字段名泄漏": fields,
        "模板残留": patterns,
        "节长变异系数": _cv([_len(s) for s in sections]),
        "句长变异系数": _cv([_len(s) for s in sentences]),
        "破折号数": text.count("——"),
        "问题总数": len(hits) + len(fields) + len(patterns),
    }


REPAIR_INSTRUCTION = """
把下面这篇文章按【修订要求】改一遍，只改表达，不许增删事实、不许改数字和链接。
直接输出修订后的全文，不要任何说明。

修订要求：
- 删掉或换掉这些词，用具体说法替代：{phrases}
- 正文里出现了英文字段名 {fields}，全部改成中文说法（如"被人复刻了 151 次"、
  "还挂着 27 个没关的问题"、"用的是 GPL-3.0"、"10 月 2 日建的"）。
- 去掉清单化写法（`**作者：**`、`**星标数：**`、"第N名｜"、"地址是 [x](…)"），
  把那些数字揉进句子。
- 把过长的段落拆成 2 段，其中一段只有一两句话。
- 各节长度拉开：次要的那节删到两三句。

原文：
"""


def build_repair_messages(broken_text: str, report: dict) -> list:
    """按自检结果生成"只改表达不改事实"的修订请求。"""
    from langchain_core.messages import HumanMessage, SystemMessage

    system = (
        "你是中文技术公众号的编辑，只做文字润色与去机器味，"
        "严禁改动仓库名、数字、日期、链接和任何事实。保持 Markdown 结构。"
    )
    human = REPAIR_INSTRUCTION.format(
        phrases="、".join(report["套话"]) or "（无）",
        fields="、".join(report["字段名泄漏"]) or "（无）",
    ) + broken_text
    return [SystemMessage(content=system), HumanMessage(content=human)]


def build_layout_seed(seed: int | None = None) -> str:
    """随机抽一套本版排版要求，拼成提示片段。

    seed 传 None 时取系统随机数；传固定值可复现同一版式（调试/回归测试用）。
    """
    import random

    rng = random.Random(seed)
    picks = [
        rng.choice(SECTIONS),
        rng.choice(OPENINGS),
        rng.choice(CLOSINGS),
        rng.choice(LINK_STYLES),
        rng.choice(DATA_HIGHLIGHTS),
    ]
    return "## 本篇排版（本次生成专用，必须遵守）\n" + "\n".join("- " + p for p in picks)


