DEFAULT_ARTICLE_STYLE = "科技种草"


def build_style_block(style: str | None) -> str:
    """把风格名解析成提示片段；未知名字回落到默认风格，不抛异常。"""
    key = (style or DEFAULT_ARTICLE_STYLE).strip()
    return ARTICLE_STYLES.get(key, ARTICLE_STYLES[DEFAULT_ARTICLE_STYLE])


def list_article_styles() -> list[str]:
    """供接口/提示词告知调用方有哪些风格可选。"""
    return list(ARTICLE_STYLES.keys())


